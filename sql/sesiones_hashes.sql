-- Sesiones con credenciales guardadas como hash.
--
-- Antes `sesiones.token`, `sesiones.refresh_token` y
-- `sesiones.refresh_anterior` guardaban la credencial en texto plano. Quien
-- pudiera leer esa tabla (un volcado, un backup mal protegido, un error de
-- otro proceso) tenia las claves para suplantar a cualquier usuario.
--
-- A partir de ahora se guarda SHA-256(credencial). El token que se envia al
-- cliente sigue siendo el original; solo cambia lo que hay en la base de datos.
--
-- Migracion idempotente con un efecto deliberado: INVALIDA LAS SESIONES
-- EXISTENTES. No hay forma de derivar el hash de las credenciales que ya se
-- guardaron en claro, asi que se borran. Los usuarios tendran que iniciar
-- sesion una vez mas y a partir de ahi la tabla solo contendra hashes.
--
-- Si se aplica dos veces, el segundo DELETE no tiene filas que borrar: es un
-- no-op, de modo que es segura de repetir.
DELETE FROM `sesiones`;
